// Local planning-prototype verification. Uses the bundled Playwright runtime.
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PROJECTS_PLAYWRIGHT_PATH || 'playwright');

(async () => {
  const options = { headless: true };
  const edge = 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe';
  if (fs.existsSync(edge)) options.executablePath = edge;
  const browser = await chromium.launch(options);
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1080 }, deviceScaleFactor: 1 });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const out = path.join(__dirname, 'screenshots');
    fs.mkdirSync(out, { recursive: true });
    const url = pathToFileURL(path.join(__dirname, 'index.html')).href;
    await page.goto(url);
    await page.screenshot({ path: path.join(out, 'overview.png'), fullPage: true });
    await page.locator('.nav [data-view="ideas"]').click();
    await page.locator('[data-action="analyze-idea"]').click();
    await page.screenshot({ path: path.join(out, 'idea.png'), fullPage: true });
    await page.locator('#idea-relation').selectOption('충돌·보류');
    assert.equal(await page.locator('[data-action="apply-idea"]').isDisabled(), true);
    await page.locator('#idea-relation').selectOption('기존 기능 확장');
    await page.locator('[data-action="apply-idea"]').click();
    assert.equal(await page.locator('[data-action="apply-idea"]').isDisabled(), true);
    await page.locator('#toast').waitFor({ state: 'hidden' });
    await page.locator('.nav [data-view="documents"]').click();
    await page.screenshot({ path: path.join(out, 'document.png'), fullPage: true });
    await page.locator('#doc-search').fill('인프라');
    assert.equal(await page.locator('.doc-item').count(), 1);
    await page.locator('#doc-search').fill('없는 문서');
    assert.match(await page.locator('#doc-list').innerText(), /검색 결과가 없습니다/);
    await page.locator('#doc-search').fill('');
    await page.locator('[data-action="edit"]').click();
    const original = await page.locator('#editor').inputValue();
    await page.locator('#editor').fill(original + '\n보존할 임시 초안');
    await page.locator('[data-doc="INF"]').first().click();
    await page.locator('[data-doc="PLAN"]').first().click();
    assert.match(await page.locator('#editor').inputValue(), /보존할 임시 초안/);
    await page.locator('[data-action="cancel-edit"]').click();
    assert.doesNotMatch(await page.locator('.doc-body').innerText(), /보존할 임시 초안/);
    await page.locator('[data-action="ai"]').click();
    await page.screenshot({ path: path.join(out, 'skill-run.png'), fullPage: true });
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('dialog').evaluate(el => el.open), false);
    assert.equal(await page.locator('[data-action="ai"]').evaluate(el => el === document.activeElement), true);
    await page.locator('[data-action="ai"]').click();
    await page.locator('[name="proposal"]').nth(1).uncheck();
    await page.locator('[data-action="apply-ai"]').click();
    assert.match(await page.locator('#editor').inputValue(), /확정본은 보존/);
    assert.doesNotMatch(await page.locator('#editor').inputValue(), /요구 변경 시 연결한 설계/);
    await page.locator('[data-action="save"]').click();
    assert.match(await page.locator('.doc-meta').innerText(), /v0.4/);
    await page.locator('[data-action="portable"]').click();
    assert.match(await page.locator('dialog').innerText(), /skills.lock.json/);
    await page.keyboard.press('Escape');
    await page.locator('.nav [data-view="tests"]').click();
    await page.locator('[data-test="TC-002"]').click();
    await page.locator('[data-test-save="TC-002"]').click();
    assert.equal(await page.locator('dialog').evaluate(el => el.open), true);
    await page.locator('[name="detail"]').fill('새 초안 생성과 확정본 불변을 확인한 시연 기록.');
    await page.locator('[data-test-save="TC-002"]').click();
    assert.equal(await page.evaluate(() => tests.find(t => t.id === 'TC-002').history.length), 2);
    await page.locator('.nav [data-view="trace"]').click();
    await page.locator('[data-action="simulate-change"]').click();
    await page.locator('[data-trace-filter="재검토"]').click();
    assert.equal(await page.locator('tbody tr').count(), 1);
    await page.locator('[data-action="review-impact"]').click();
    await page.locator('[data-action="confirm-impact"]').click();
    assert.equal(await page.locator('tbody tr').count(), 1);
    await page.screenshot({ path: path.join(out, 'trace.png'), fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 });
    await mobile.goto(url + '#ideas');
    await mobile.locator('[data-action="analyze-idea"]').click();
    await mobile.screenshot({ path: path.join(out, 'mobile.png'), fullPage: true });
    assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await mobile.locator('.nav [data-view="documents"]').click();
    await mobile.screenshot({ path: path.join(out, 'mobile-document.png'), fullPage: true });
    assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ result: 'passed', browser: browser.version(), viewport: [1440, 1080], mobile: [390, 844], checks: ['idea conversion and conflict hold', 'duplicate apply blocked', 'document search and empty result', 'draft retained across selection', 'cancel preserves document', 'dialog Escape and focus return', 'skill selection and explicit save', 'independent document contract', 'required evidence and prior test run retained', 'impact review preserves pending actions', 'no page overflow', 'no page errors'], screenshots: fs.readdirSync(out) }, null, 2));
  } finally {
    await browser.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
